def flattened_questions() -> list[dict[str, str | int]]:
    questions: list[dict[str, str | int]] = []
    for story in JOURNEY_STORIES:
        for offset, prompt in enumerate(story["questions"], start=1):
            questions.append(
                {
                    "story_id": story["story_id"],
                    "story_num": story["story_num"],
                    "question_num": ((story["story_num"] - 1) * 10) + offset,
                    "story_question_num": offset,
                    "prompt_text": prompt,
                }
            )
    return questions